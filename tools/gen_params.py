"""Generates Source/ParamTable.h from the web prototype's parameter table (dumped as JSON),
so the plugin's host parameters always match the prototype's dials: same IDs, ranges, curves.
New FLUIDIC instances default to Sine Meditation and FLUIDIC FX to Break Drips, as the prototype does."""
import json, sys
d = json.load(open(sys.argv[1])); out = sys.argv[2]
sine = d['sine']; fxd = d.get('fxDefault', {})
UNITS = {'rhy.bpm':'bpm','in.drive':'times','rhy.sense':'pctoff','in.chop':'pctoff','in.follow':'pctoff','flow.slosh':'pctoff','flow.turb':'pctoff','flow.cascade':'pctoff','flow.sway':'Hz','flow.ripple':'pctoff','flow.collide':'pctoff','drip.cutoff':'Hz','filt.cutoff':'Hz','drip.fall':'ms','filt.attack':'s','filt.decay':'s','amp.a':'s','amp.d':'s','amp.r':'s',
         'fx.delayTime':'ms','fx.revSize':'s','filt.lfoRate':'Hz','drip.sweep':'oct','filt.env':'bi','exc.octave':'oct','drip.density':'x','drip.size':'x'}
rows = []
for p in d['params']:
    pid = p['id']; deflt = sine.get(pid, p['def']); dfx = fxd.get(pid, p['fxDef'] if p.get('fxDef') is not None else p['def'])
    flags = f'{"true" if p.get("synthOnly") else "false"}, {"true" if p.get("fxOnly") else "false"}'
    if p['type'] == 'enum':
        keys = [o[0] for o in p['options']]; labels = [o[1] for o in p['options']]
        rows.append(f'    {{ "{pid}", "{p["name"]}", Kind::choice, 0.0f, {float(len(keys)-1)!r}f, {float(keys.index(deflt))!r}f, false, '
                    f'{{ {", ".join(chr(34)+k+chr(34) for k in keys)} }}, {{ {", ".join(chr(34)+l+chr(34) for l in labels)} }}, "", {float(keys.index(dfx))!r}f, {flags} }},')
    else:
        kind = 'Kind::integer' if p['step'] == 1 else 'Kind::number'
        rows.append(f'    {{ "{pid}", "{p["name"]}", {kind}, {float(p["min"])!r}f, {float(p["max"])!r}f, {float(deflt)!r}f, {"true" if p["log"] else "false"}, {{}}, {{}}, "{UNITS.get(pid, "%")}", {float(dfx)!r}f, {flags} }},')
src = '''#pragma once
// GENERATED by tools/gen_params.py from the web prototype's parameter table — do not edit by hand.
// IDs are stable: they are what DAWs store for automation, so never rename one.
#include <vector>
namespace fluidic
{
enum class Kind { number, integer, choice };
struct ParamSpec
{
    const char* id; const char* name; Kind kind; float min, max, def; bool log;
    std::vector<const char*> keys, labels;   // choice parameters: UI keys and display names
    const char* unit;                         // display: "%", "Hz", "ms", "s", "oct", "bi", "x"
    float defFx;                              // FLUIDIC FX opens on Drippiness; FLUIDIC on Sine Meditation
    bool synthOnly, fxOnly;                   // which plugin the parameter belongs to
};
inline const std::vector<ParamSpec>& paramTable()
{
    static const std::vector<ParamSpec> table {
''' + '\n'.join(rows) + '''
    };
    return table;
}
} // namespace fluidic
'''
open(out, 'w').write(src); print('wrote', out, len(rows), 'parameters')
